# Sanity check (执行时一次):
assert len(CORPUS) >= 2000, f"语料长度 {len(CORPUS)} 不足 2000 字符"

# ---------------------------------------------------------------------------
# system / 指令模板
# ---------------------------------------------------------------------------
SYSTEM_SHORT = "你是一个简洁的助手。回答必须精炼、直接，不要展开论述。"
SYSTEM_LONG = "你是一个善于详细解释的助手。请充分展开论证，分点说明，给出完整的推理过程与示例。"

USER_SUFFIX_SHORT = "\n\n请用一两句话简短回答上述问题。"
USER_SUFFIX_LONG = "\n\n请围绕上述材料，分点详细展开论述，给出完整推理过程与示例。"

# 短输入用的问题（不依赖语料）
_SHORT_QUESTIONS = [
    "请解释一下什么是大语言模型的 KV 缓存，以及它为什么对推理吞吐至关重要？",
    "在 LLM 推理服务中，TTFT 和 TPOT 分别衡量什么？为什么要分别看？",
    "为什么相同模型在不同 batch size 下，单请求延迟差异会很大？",
    "解释一下 prefill 和 decode 阶段在 LLM 推理中的区别。",
    "为什么并发数越高，单个请求的 TPOT 通常会变差？",
    "什么是推测式解码（speculative decoding）？它的收益来自哪里？",
    "在多卡张量并行的推理中，通信开销如何影响延迟？",
    "为什么长输入场景下，prefill 显存占用是关键瓶颈？",
]


# ---------------------------------------------------------------------------
# 构造函数
# ---------------------------------------------------------------------------
def _take_corpus(target_chars: int) -> str:
    """从 CORPUS 头部裁剪出指定字符数，必要时拼接多遍以满足长度。"""
    if target_chars <= len(CORPUS):
        return CORPUS[:target_chars]
    repeats = (target_chars // len(CORPUS)) + 1
    return (CORPUS * repeats)[:target_chars]


def make_prompt(
    target_input_tokens: int,
    want_long_output: bool,
    rng: random.Random | None = None,
) -> Tuple[str, str]:
    """构造 (system, user) prompt。

    - target_input_tokens 小（短输入）：从短问题池采样，user prompt 字符数约等于该问题长度
    - target_input_tokens 大（长输入）：从 CORPUS 切出 target_input_tokens-30 字符，
      拼接一个"基于以上材料，请…"前缀。
    - want_long_output 控制 system prompt 与 user suffix 的风格引导。

    1 中文字符 ≈ 1 token 的近似关系。指令本身也占 token，因此从 target 中预留 30 字符余量。
    """
    rng = rng or random.Random()
    user_suffix = USER_SUFFIX_LONG if want_long_output else USER_SUFFIX_SHORT
    system = SYSTEM_LONG if want_long_output else SYSTEM_SHORT

    # 短输入：直接用预置短问题（避免过度切语料导致的语义混乱）
    if target_input_tokens <= 256:
        question = rng.choice(_SHORT_QUESTIONS)
        # 如果问题字符数距离目标差太多，可以叠加一句
        while len(question) + 30 < target_input_tokens - 32:
            question = question + " " + rng.choice(_SHORT_QUESTIONS)
        user = question + user_suffix
        return system, user

    # 长输入：基于语料构造
    body_chars = max(64, target_input_tokens - 40)  # 40 是前后缀冗余
    body = _take_corpus(body_chars)
    user = "请阅读以下材料：\n\n" + body + user_suffix
    return system, user
